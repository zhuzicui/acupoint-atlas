# Head detail -> body view transform
HEAD2BODY = {"face": "front", "headside": "side", "headback": "back"}
S = 130 / 320
def to_body(x, y):
    return round(200 + (x - 200) * S, 1), round(40 + (y - 40) * S, 1)

MIDLINE_PREFIX = ("GV", "CV")
NON_BILATERAL = {"EX-HN10", "EX-HN11", "EX-HN12", "EX-HN13", "EX-HN1"}
def bilateral(code):
    return not code.startswith(MIDLINE_PREFIX) and code not in NON_BILATERAL
